/**
 * The TS oracle for wiki game info and the umu id lookup (86-06 Task 3, D-09, D-10, D-23 and SC1).
 * It drives the real `getWikiGameInfo` (the 30 day cache, the three stale rules, the platform
 * branches, PCGamingWiki, AppleGamingWiki, the CrossOver index, GamesDB, HowLongToBeat, ProtonDB,
 * Steam Deck) and `getUmuId` over real `CacheStore` files, a pinned clock and the shared recorder.
 *
 * All eight sources are public and keyless, so live cases were recorded from the real services
 * (`GAMELIB_INFO_ORACLE=record`). Error paths no live service shows on demand (a PCGamingWiki 403,
 * a HowLongToBeat 403 that forces a re-init, an ambiguous HLTB search, a umu 500) are synthetic
 * responses marked `synthetic: true`. A synthetic matches by method and path only, so a case that
 * uses one runs on a platform where that path is not shared by two hosts.
 *
 * GOG titles go through the real `GOGGame.getExtraInfo` and `GOGLibraryManager`
 * (`createReqsArray`, `getProductApi`, `getGamesData`, `getGamesdbData`) over a stub of the few
 * deps they read, so the storeUrl and its `af.gog.com` rewrite are what TS code computes. D-23:
 * the GOG requests Rust will not make are marked `tsOnly: true` (every `getExtraInfo` request: the
 * requirements and store-link `v2/games` reads and the changelog `products` read), and the one
 * unauthenticated GET Rust makes in their place, `v2/games/<id>?locale=en-US`, is also fetched in
 * record mode as a `rustOnly: true` exchange so the Rust replay has a response for it. The GamesDB
 * read is the same URL on both sides and stays a shared exchange. The golden also records the
 * keys TS wrote into GOG's `gog_api_info` cache (`gogApiInfoWrites`), which Rust does not write.
 *
 * Starting state (`wikiCache`, `umuCache`, `crossoverIndex`) is generated by this test through the
 * real stores and written to `state/wiki/<case>` in record and write modes; the CrossOver index
 * seeded there is the live payload recorded for 86-06 Task 2. Every case then runs from that
 * committed folder.
 *
 * Record:  GAMELIB_INFO_ORACLE=record pnpm exec jest --runTestsByPath <this file>
 * Write:   GAMELIB_WRITE_INFO_GOLDEN=1 pnpm exec jest --runTestsByPath <this file>
 * Compare: pnpm exec jest --runTestsByPath <this file>
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs'
import { join } from 'path'
import { gunzipSync } from 'node:zlib'
import {
  assertLiveRecorded,
  assertManifest,
  expectEmptyCasesToFail,
  loadCases,
  mockPlatform,
  normaliseDates,
  pinClock,
  snapshotFiles,
  stateDir,
  syncManifest,
  withOracleProfile,
  writeOrCompareGolden,
  type OraclePlatform
} from './harness'
import {
  installAdapter,
  installRecorder,
  oracleMode,
  recordedCaseDir,
  type RustOnlyRequest,
  type SyntheticResponse
} from './recorder'

const SLICE = 'wiki'
/** The floor this test carries; the committed MANIFEST must be at or above it. */
const FLOOR = 25

const ORACLE_NOW = Date.UTC(2026, 10, 22, 12, 0, 0)
const CROSSOVER_LIVE_CASE = 'live-fresh-fetch-mac'

interface GameRef {
  runner: 'steam' | 'legendary' | 'gog' | 'nile' | 'sideload'
  app_name: string
  title: string
}

type Op =
  | { op: 'wiki'; game: GameRef; forceRefresh?: boolean }
  | { op: 'umu'; runner: GameRef['runner']; app_name: string }
  | { op: 'advance'; minutes: number }

interface SyntheticSpec {
  method: string
  /** Matched against the request path only, so the host is not part of it. */
  path: string
  status?: number
  text?: string
  json?: unknown
  /** The body is a file of an already recorded case (a real response reused as a synthetic body). */
  fromRecorded?: { case: string; file: string }
  networkError?: boolean
}

interface WikiCase {
  id: string
  note?: string
  platform: OraclePlatform
  live?: boolean
  /** Entries of the wiki info store: key is the cache title, written `ageMinutes` before the clock. */
  wikiCache?: { title: string; ageMinutes: number; value: unknown }[]
  /** Entries of the umu store. */
  umuCache?: { key: string; ageMinutes: number; value: string | null }[]
  /** Seed the CrossOver index store with the live payload recorded for Task 2, fresh. */
  crossoverIndex?: boolean
  ops: Op[]
  synthetic?: SyntheticSpec[]
}

const cases = loadCases<WikiCase>(SLICE)

function crossoverPayload(): unknown {
  const dir = recordedCaseDir('crossover', CROSSOVER_LIVE_CASE)
  const exchanges = JSON.parse(
    readFileSync(join(dir, 'exchanges.json'), 'utf8')
  ) as { response: { bodyFile?: string } }[]
  const file = exchanges[0]?.response.bodyFile
  if (!file) throw new Error('the crossover live recording is missing')
  return JSON.parse(
    gunzipSync(readFileSync(join(dir, file))).toString('utf8')
  ) as unknown
}

function syntheticResponses(c: WikiCase): SyntheticResponse[] {
  if (oracleMode() !== 'record') return []
  return (c.synthetic ?? []).map((spec) => {
    const body = spec.fromRecorded
      ? readFileSync(
          join(
            recordedCaseDir(SLICE, spec.fromRecorded.case),
            spec.fromRecorded.file
          ),
          'utf8'
        )
      : (spec.text ??
        (spec.json === undefined ? '' : JSON.stringify(spec.json)))
    return {
      method: spec.method,
      path: spec.path,
      status: spec.status ?? 200,
      headers: {
        'content-type':
          spec.json === undefined && !spec.fromRecorded
            ? 'text/plain'
            : 'application/json'
      },
      body,
      ...(spec.networkError ? { networkError: true } : {})
    }
  })
}

type Modules = {
  wiki: typeof import('backend/wiki_game_info/wiki_game_info')
  umu: typeof import('backend/wiki_game_info/umu/utils')
  hltb: typeof import('backend/wiki_game_info/howlongtobeat/utils')
  wikiStores: typeof import('backend/wiki_game_info/stores')
  crossoverStores: typeof import('backend/crossover_index/stores')
  crossoverFetcher: typeof import('backend/crossover_index/fetcher')
  crossoverIndex: typeof import('backend/crossover_index/index')
  gogLibrary: typeof import('backend/storeManagers/gog/library')
  gogGames: typeof import('backend/storeManagers/gog/games')
}
let mods: Modules

let restoreClock: () => void
beforeAll(async () => {
  restoreClock = pinClock(ORACLE_NOW)
  installAdapter()
  mods = {
    wiki: await import('backend/wiki_game_info/wiki_game_info'),
    umu: await import('backend/wiki_game_info/umu/utils'),
    hltb: await import('backend/wiki_game_info/howlongtobeat/utils'),
    wikiStores: await import('backend/wiki_game_info/stores'),
    crossoverStores: await import('backend/crossover_index/stores'),
    crossoverFetcher: await import('backend/crossover_index/fetcher'),
    crossoverIndex: await import('backend/crossover_index/index'),
    gogLibrary: await import('backend/storeManagers/gog/library'),
    gogGames: await import('backend/storeManagers/gog/games')
  }
})
afterAll(() => {
  restoreClock()
  syncManifest(SLICE, cases, FLOOR)
})

/** Generates `state/wiki/<case>` through the real stores (record and write modes only). */
async function writeState(c: WikiCase): Promise<void> {
  if (oracleMode() === 'compare') return
  const dir = stateDir(SLICE, c.id)
  rmSync(dir, { recursive: true, force: true })
  if (!c.wikiCache && !c.umuCache && !c.crossoverIndex) return
  await withOracleProfile(({ userData, root }) => {
    const { wikiGameInfoStore, umuStore } =
      mods.wikiStores.createWikiGameInfoStores({ root })
    for (const entry of c.wikiCache ?? []) {
      jest.setSystemTime(ORACLE_NOW - entry.ageMinutes * 60_000)
      wikiGameInfoStore.set(entry.title, entry.value as never)
    }
    for (const entry of c.umuCache ?? []) {
      jest.setSystemTime(ORACLE_NOW - entry.ageMinutes * 60_000)
      umuStore.set(entry.key, entry.value)
    }
    if (c.crossoverIndex) {
      const { crossoverIndexStore } =
        mods.crossoverStores.createCrossoverIndexStores({ root })
      jest.setSystemTime(ORACLE_NOW - 60 * 60_000)
      crossoverIndexStore.set('index', {
        data: crossoverPayload(),
        fetchedAt: ORACLE_NOW - 60 * 60_000
      })
    }
    jest.setSystemTime(ORACLE_NOW)
    for (const [rel, bytes] of Object.entries(snapshotFiles(userData))) {
      const target = join(dir, rel)
      mkdirSync(join(target, '..'), { recursive: true })
      writeFileSync(target, normaliseDates(bytes))
    }
  })
}

function gogIds(c: WikiCase): string[] {
  return [
    ...new Set(
      c.ops.flatMap((op) =>
        op.op === 'wiki' && op.game.runner === 'gog' ? [op.game.app_name] : []
      )
    )
  ]
}

describe('wiki oracle', () => {
  it('has at least the floor of cases, and the manifest agrees', () => {
    assertManifest(SLICE, cases, FLOOR)
  })

  it('an empty case list fails the manifest guard', () => {
    expectEmptyCasesToFail(SLICE, FLOOR)
  })

  it('every live case names a recording in compare and write modes', () => {
    for (const c of cases) assertLiveRecorded(SLICE, c)
  })

  it.each(cases.map((c) => [c.id, c] as const))('%s', async (_id, c) => {
    const ids = gogIds(c)
    const tsOnly = ids.flatMap((id) => [
      `GET https://api.gog.com/v2/games/${id}?locale=en-US`,
      `GET https://api.gog.com/products/${id}?*`
    ])
    const rustOnly: RustOnlyRequest[] = ids.map((id) => ({
      method: 'GET',
      url: `https://api.gog.com/v2/games/${id}?locale=en-US`
    }))
    const recorder = installRecorder({
      slice: SLICE,
      caseId: c.id,
      synthetic: syntheticResponses(c),
      tsOnly,
      rustOnly
    })
    await writeState(c)
    const restorePlatform = mockPlatform(c.platform)
    try {
      const outcome = await withOracleProfile(
        async ({ userData, root }) => {
          const wikiGameInfo = mods.wikiStores.createWikiGameInfoStores({
            root
          })
          const crossoverIndexStores =
            mods.crossoverStores.createCrossoverIndexStores({ root })
          const crossoverFetcher =
            mods.crossoverFetcher.createCrossoverIndexFetcher({
              clock: { now: () => Date.now() },
              paths: { publicDir: join(userData, 'public') }
            })
          const crossoverLookups = mods.crossoverIndex.createCrossoverIndex({
            fetcher: crossoverFetcher
          })

          const gogApiInfoWrites: string[] = []
          const library = new mods.gogLibrary.default({
            onlineMonitor: { isOnline: () => true },
            stores: {
              gog: {
                apiInfoCache: {
                  get: () => undefined,
                  set: (key: string) => {
                    gogApiInfoWrites.push(key)
                  }
                }
              }
            }
          } as never)
          const gogInfo = new Map<string, unknown>()
          jest
            .spyOn(library, 'getGameInfo')
            .mockImplementation(((id: string) => gogInfo.get(id)) as never)
          const gogDeps = { libraryManagers: { gog: library } } as never

          const deps = {
            libraryManagers: { gog: library },
            stores: { wikiGameInfo, crossoverIndex: crossoverIndexStores },
            infoCaches: { hltb: mods.hltb.createHltbCredentials() },
            appRuntime: { crossoverIndex: crossoverLookups }
          } as never

          const gameFor = (ref: GameRef) => {
            if (ref.runner === 'gog') {
              gogInfo.set(ref.app_name, {
                app_name: ref.app_name,
                runner: 'gog',
                title: ref.title,
                is_mac_native: false,
                is_linux_native: false,
                install: {},
                is_installed: false
              })
              return new mods.gogGames.default(ref.app_name, gogDeps)
            }
            return {
              getGameInfo: () => ({
                app_name: ref.app_name,
                runner: ref.runner,
                title: ref.title
              }),
              getExtraInfo: () => Promise.resolve({})
            }
          }

          const results: unknown[] = []
          for (const op of c.ops) {
            const requestsBefore = recorder.requested.length
            let entry: Record<string, unknown>
            try {
              if (op.op === 'advance') {
                jest.setSystemTime(Date.now() + op.minutes * 60_000)
                entry = { op: 'advance', minutes: op.minutes }
              } else if (op.op === 'umu') {
                entry = {
                  op: 'umu',
                  runner: op.runner,
                  app_name: op.app_name,
                  result: await mods.umu.getUmuId(deps, op.app_name, op.runner)
                }
              } else {
                entry = {
                  op: 'wiki',
                  game: op.game.title,
                  forceRefresh: op.forceRefresh ?? false,
                  result: await mods.wiki.getWikiGameInfo(
                    deps,
                    gameFor(op.game) as never,
                    op.forceRefresh
                  )
                }
              }
            } catch (error) {
              entry = {
                op: op.op,
                error: error instanceof Error ? error.message : String(error)
              }
            }
            results.push({
              ...entry,
              requestsMade: recorder.requested.length - requestsBefore
            })
          }

          const files: Record<string, Buffer> = {}
          for (const [rel, bytes] of Object.entries(snapshotFiles(userData))) {
            files[rel] = normaliseDates(bytes)
          }
          return { results, files, gogApiInfoWrites }
        },
        stateDir(SLICE, c.id)
      )

      await recorder.finish()
      writeOrCompareGolden(SLICE, c.id, {
        result: {
          ops: outcome.results,
          requests: recorder.requested,
          gogApiInfoWrites: outcome.gogApiInfoWrites
        },
        files: outcome.files
      })
    } finally {
      restorePlatform()
      jest.restoreAllMocks()
      jest.setSystemTime(ORACLE_NOW)
    }
  })
})
