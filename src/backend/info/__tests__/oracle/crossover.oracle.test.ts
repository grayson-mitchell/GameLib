/**
 * The TS oracle for the CrossOver compatibility index (86-06 Task 2, D-09, D-10 and SC1). It
 * drives the real fetcher (`loadIndex`: fetch, gunzip, schema, keep-last-good, the 5 minute
 * failure back-off, the bundled fallback), the lookups (`getCodeweaversFromIndex`,
 * `crossoverIndexHas`, `buildIndexResolver`) and `buildCrossoverRatingMap`, over real
 * `CacheStore` files, a pinned clock and the shared recorder.
 *
 * The index is a public GitHub release asset and needs no key, so the live cases were recorded
 * once from the real URL. Everything the live service cannot show on demand (a version 2
 * payload, a rating of 6, a truncated list, an over-5-MiB body, a 500, a transport failure) is a
 * synthetic response, marked `synthetic: true` in the recording; the golden is still the TS
 * output on it. Synthetic bodies are built from the live payload: no payload byte is typed here.
 *
 * Starting state (`cache`, `bundled`) is generated by this test through the real `CacheStore` and
 * written to `state/crossover/<case>` in record and write modes, then every case runs from that
 * committed folder. The Rust side seeds its profile from the same folder. The bundled snapshot is
 * `public/crossover-index.json.gz` inside the state folder (the plan's temp publicDir) and is
 * left out of the `after/` files.
 *
 * Record:  GAMELIB_INFO_ORACLE=record pnpm exec jest --runTestsByPath <this file>
 *          (the first case is the live one; later cases read its recorded bytes)
 * Write:   GAMELIB_WRITE_INFO_GOLDEN=1 pnpm exec jest --runTestsByPath <this file>
 * Compare: pnpm exec jest --runTestsByPath <this file>
 */
import { createHash } from 'crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs'
import { join } from 'path'
import { gunzipSync, gzipSync } from 'node:zlib'
import {
  assertLiveRecorded,
  assertManifest,
  expectEmptyCasesToFail,
  loadCases,
  mockPlatform,
  normaliseDates,
  pinClock,
  snapshotFiles,
  stateDir,
  syncManifest,
  withOracleProfile,
  writeOrCompareGolden,
  type OraclePlatform
} from './harness'
import {
  installAdapter,
  installRecorder,
  oracleMode,
  recordedCaseDir,
  type SyntheticResponse
} from './recorder'

const SLICE = 'crossover'
/** The floor this test carries; the committed MANIFEST must be at or above it. */
const FLOOR = 12

const ORACLE_NOW = Date.UTC(2026, 10, 22, 12, 0, 0)
const LIVE_CASE = 'live-fresh-fetch-mac'
const INDEX_PATH =
  '/grayson-mitchell/GameLib/releases/download/crossover-index/crossover-index.json.gz'
const MAX_CONTENT_LENGTH = 5 * 1024 * 1024

interface Game {
  runner: string
  app_name: string
  title: string
}

type Op =
  | { op: 'load'; url?: string }
  | { op: 'codeweavers'; game: Game }
  | { op: 'has'; game: Game }
  | { op: 'resolver'; games: Game[] }
  | { op: 'ratingMap' }
  | { op: 'advance'; minutes: number }

interface SyntheticSpec {
  status?: number
  text?: string
  /** The live gz bytes as they were recorded. */
  rawLive?: boolean
  /** A gzip of the live payload with one fault: version-2, rating-6, entries-999, generatedAt-garbage. */
  mutate?: string
  /** A body of this many zero bytes. */
  zeroBytes?: number
  networkError?: boolean
}

interface CrossoverCase {
  id: string
  note?: string
  platform: OraclePlatform
  live?: boolean
  /** The store holds the index under `index`, fetched `ageMinutes` before the oracle clock. */
  cache?: { index: 'old' | 'live'; ageMinutes: number }
  bundled?: 'live' | 'invalid'
  library?: Game[]
  ops: Op[]
  synthetic?: SyntheticSpec[]
}

const cases = loadCases<CrossoverCase>(SLICE)

interface IndexPayload {
  version: number
  generatedAt: string
  entries: { name: string; rating: number; steamid?: string }[]
}

function liveGz(): Buffer {
  const dir = recordedCaseDir(SLICE, LIVE_CASE)
  const exchanges = JSON.parse(
    readFileSync(join(dir, 'exchanges.json'), 'utf8')
  ) as { response: { bodyFile?: string } }[]
  const file = exchanges[0]?.response.bodyFile
  if (!file) throw new Error(`${LIVE_CASE} has no recorded index body`)
  return readFileSync(join(dir, file))
}

function livePayload(): IndexPayload {
  return JSON.parse(gunzipSync(liveGz()).toString('utf8')) as IndexPayload
}

const gz = (payload: unknown): Buffer =>
  gzipSync(Buffer.from(JSON.stringify(payload), 'utf8'))

function mutated(kind: string): Buffer {
  const base = livePayload()
  if (kind === 'version-2') return gz({ ...base, version: 2 })
  if (kind === 'generatedAt-garbage')
    return gz({ ...base, generatedAt: 'not-a-date' })
  if (kind === 'entries-999') {
    return gz({ ...base, entries: base.entries.slice(0, 999) })
  }
  if (kind === 'rating-6') {
    const entries = base.entries.map((e, i) =>
      i === 0 ? { ...e, rating: 6 } : e
    )
    return gz({ ...base, entries })
  }
  throw new Error(`unknown mutation ${kind}`)
}

/** The first 1000 live entries under an older `generatedAt`: a valid last-good that differs. */
function oldPayload(): IndexPayload {
  const base = livePayload()
  return {
    version: 1,
    generatedAt: '2026-11-01T00:00:00.000Z',
    entries: base.entries.slice(0, 1000)
  }
}

function syntheticResponses(c: CrossoverCase): SyntheticResponse[] {
  if (oracleMode() !== 'record') return []
  return (c.synthetic ?? []).map((spec) => {
    const base = {
      method: 'GET',
      path: INDEX_PATH,
      status: spec.status ?? 200,
      headers: { 'content-type': 'application/octet-stream' }
    }
    if (spec.networkError) return { ...base, body: '', networkError: true }
    if (spec.text !== undefined) return { ...base, body: spec.text }
    if (spec.rawLive) {
      return { ...base, body: '', bodyBase64: liveGz().toString('base64') }
    }
    if (spec.mutate) {
      return {
        ...base,
        body: '',
        bodyBase64: mutated(spec.mutate).toString('base64')
      }
    }
    if (spec.zeroBytes !== undefined) {
      return {
        ...base,
        body: '',
        bodyBase64: Buffer.alloc(spec.zeroBytes).toString('base64')
      }
    }
    throw new Error(`${c.id}: empty synthetic spec`)
  })
}

type Modules = {
  fetcher: typeof import('backend/crossover_index/fetcher')
  index: typeof import('backend/crossover_index/index')
  stores: typeof import('backend/crossover_index/stores')
  ratingMap: typeof import('backend/crossover_index/crossoverRatingMap')
  testRoot: typeof import('backend/testUtils/testStoreRoot')
}
let mods: Modules

let restoreClock: () => void
beforeAll(async () => {
  restoreClock = pinClock(ORACLE_NOW)
  installAdapter()
  mods = {
    fetcher: await import('backend/crossover_index/fetcher'),
    index: await import('backend/crossover_index/index'),
    stores: await import('backend/crossover_index/stores'),
    ratingMap: await import('backend/crossover_index/crossoverRatingMap'),
    testRoot: await import('backend/testUtils/testStoreRoot')
  }
})
afterAll(() => {
  restoreClock()
  syncManifest(SLICE, cases, FLOOR)
})

/** Generates `state/crossover/<case>` through the real store (record and write modes only). */
async function writeState(c: CrossoverCase): Promise<void> {
  if (oracleMode() === 'compare') return
  const dir = stateDir(SLICE, c.id)
  rmSync(dir, { recursive: true, force: true })
  if (!c.cache && !c.bundled) return
  await withOracleProfile(({ userData, root }) => {
    if (c.cache) {
      const { crossoverIndexStore } = mods.stores.createCrossoverIndexStores({
        root
      })
      const fetchedAt = ORACLE_NOW - c.cache.ageMinutes * 60_000
      jest.setSystemTime(fetchedAt)
      crossoverIndexStore.set('index', {
        data: c.cache.index === 'live' ? livePayload() : oldPayload(),
        fetchedAt
      })
      jest.setSystemTime(ORACLE_NOW)
    }
    const files = snapshotFiles(userData)
    for (const [rel, bytes] of Object.entries(files)) {
      const target = join(dir, rel)
      mkdirSync(join(target, '..'), { recursive: true })
      writeFileSync(target, normaliseDates(bytes))
    }
    if (c.bundled) {
      const target = join(dir, 'public', 'crossover-index.json.gz')
      mkdirSync(join(target, '..'), { recursive: true })
      writeFileSync(
        target,
        c.bundled === 'live' ? liveGz() : mutated('version-2')
      )
    }
  })
}

const canonical = (value: unknown): string => {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`
  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>).sort(
      ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)
    )
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonical(v)}`).join(',')}}`
  }
  return JSON.stringify(value)
}

const describeIndex = (data: IndexPayload | null): unknown =>
  data === null
    ? null
    : {
        generatedAt: data.generatedAt,
        entryCount: data.entries.length,
        sha256: createHash('sha256').update(canonical(data)).digest('hex')
      }

describe('crossover oracle', () => {
  it('has at least the floor of cases, and the manifest agrees', () => {
    assertManifest(SLICE, cases, FLOOR)
  })

  it('an empty case list fails the manifest guard', () => {
    expectEmptyCasesToFail(SLICE, FLOOR)
  })

  it('every live case names a recording in compare and write modes', () => {
    for (const c of cases) assertLiveRecorded(SLICE, c)
  })

  it.each(cases.map((c) => [c.id, c] as const))('%s', async (_id, c) => {
    const recorder = installRecorder({
      slice: SLICE,
      caseId: c.id,
      synthetic: syntheticResponses(c)
    })
    await writeState(c)
    const restorePlatform = mockPlatform(c.platform)
    try {
      const outcome = await withOracleProfile(
        async ({ userData, root }) => {
          const crossoverIndex = mods.stores.createCrossoverIndexStores({
            root
          })
          const deps = { stores: { crossoverIndex } }
          const fetcher = mods.fetcher.createCrossoverIndexFetcher({
            clock: { now: () => Date.now() },
            paths: { publicDir: join(userData, 'public') }
          })
          const lookups = mods.index.createCrossoverIndex({ fetcher })

          const byRunner: Record<string, Game[]> = {}
          for (const g of c.library ?? []) (byRunner[g.runner] ??= []).push(g)
          const libraryManagers = Object.fromEntries(
            Object.entries(byRunner).map(([runner, games]) => [
              runner,
              { getListOfGames: () => games }
            ])
          )

          const results: unknown[] = []
          for (const op of c.ops) {
            const requestsBefore = recorder.requested.length
            let entry: Record<string, unknown>
            try {
              if (op.op === 'advance') {
                jest.setSystemTime(Date.now() + op.minutes * 60_000)
                entry = { op: 'advance', minutes: op.minutes }
              } else if (op.op === 'load') {
                const desc = op.url
                  ? { ...mods.index.crossoverIndexDescriptor, url: op.url }
                  : mods.index.crossoverIndexDescriptor
                entry = {
                  op: 'load',
                  result: describeIndex(
                    (await fetcher.loadIndex(deps, desc)) as IndexPayload | null
                  )
                }
              } else if (op.op === 'codeweavers') {
                entry = {
                  op: 'codeweavers',
                  game: op.game.app_name,
                  result: await lookups.getCodeweaversFromIndex(
                    deps,
                    op.game as never
                  )
                }
              } else if (op.op === 'has') {
                entry = {
                  op: 'has',
                  game: op.game.app_name,
                  result: lookups.crossoverIndexHas(deps, op.game as never)
                }
              } else if (op.op === 'resolver') {
                const resolve = await lookups.buildIndexResolver(deps)
                entry = {
                  op: 'resolver',
                  result: Object.fromEntries(
                    op.games.map((g) => [
                      `${g.runner}:${g.app_name}`,
                      resolve(g as never)
                    ])
                  )
                }
              } else {
                entry = {
                  op: 'ratingMap',
                  result: await mods.ratingMap.buildCrossoverRatingMap({
                    libraryManagers,
                    stores: { crossoverIndex },
                    appRuntime: { crossoverIndex: lookups }
                  } as never)
                }
              }
            } catch (error) {
              entry = {
                op: op.op,
                error: error instanceof Error ? error.message : String(error)
              }
            }
            results.push({
              ...entry,
              requestsMade: recorder.requested.length - requestsBefore
            })
          }

          const files: Record<string, Buffer> = {}
          for (const [rel, bytes] of Object.entries(snapshotFiles(userData))) {
            if (rel.startsWith('public/')) continue
            files[rel] = normaliseDates(bytes)
          }
          return { results, files }
        },
        stateDir(SLICE, c.id)
      )

      await recorder.finish()
      writeOrCompareGolden(SLICE, c.id, {
        result: { ops: outcome.results, requests: recorder.requested },
        files: outcome.files
      })
    } finally {
      restorePlatform()
      jest.setSystemTime(ORACLE_NOW)
    }
  })

  it('the over-5-MiB synthetic really is over the cap', () => {
    const over = cases
      .flatMap((c) => c.synthetic ?? [])
      .find((s) => s.zeroBytes)
    expect(over?.zeroBytes).toBeGreaterThan(MAX_CONTENT_LENGTH)
  })
})
