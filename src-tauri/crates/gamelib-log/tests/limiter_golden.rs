//! The gamelib.log rate limiter, replayed against a scripted clock (Phase 84 plan 04, D-14).
//!
//! The source of truth is 84-CONTEXT D-14: lines with the same prefix, level and body are counted
//! per 60 s window, the first 5 per window are written, the rest are suppressed, and when the
//! window closes one line with the same level and prefix and the body
//! `<first 200 chars of the body> (repeated <K> more times)` is written. `fixtures/limiter/
//! expected.gamelib.log` is hand-written from those rules and the line format (README section 6:
//! a hand-written expectation, no TS oracle exists for a limiter), not generated by the code under
//! test.
//!
//! `fixtures/limiter/script.json` is the input: `t` is seconds on the scripted clock, which starts
//! at 13:05:00 UTC (offset 0). A step is a line (`level`, `prefix`, `msg`), a writer tick
//! (`"tick": true`) or a flush (`"flush": true`). The writer is asynchronous, so every step ends
//! with a barrier before the clock moves.

use std::fs;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Duration;

use gamelib_core::clock::Clock;
use gamelib_core::paths::{join, Platform};
use gamelib_log::writer::{LogConfig, Logger, TzOffset};
use gamelib_log::{Level, Prefix};
use gamelib_testutil::FakeHome;
use serde::Deserialize;

const SCRIPT: &str = include_str!("fixtures/limiter/script.json");
const EXPECTED: &str = include_str!("fixtures/limiter/expected.gamelib.log");

/// 13:05:00 on 1970-01-01 at UTC.
const BASE_MS: u64 = 47_100_000;

struct ScriptClock(Arc<AtomicU64>);
impl Clock for ScriptClock {
    fn now_ms(&self) -> u64 {
        self.0.load(Ordering::SeqCst)
    }
}

struct Utc;
impl TzOffset for Utc {
    fn offset_minutes(&self, _epoch_ms: u64) -> i32 {
        0
    }
}

#[derive(Deserialize)]
struct Script {
    steps: Vec<Step>,
}

#[derive(Deserialize)]
struct Step {
    t: u64,
    level: Option<String>,
    prefix: Option<String>,
    msg: Option<String>,
    #[serde(default)]
    tick: bool,
    #[serde(default)]
    flush: bool,
}

#[test]
fn the_scripted_clock_golden_matches_the_hand_written_gamelib_log() {
    let script: Script = serde_json::from_str(SCRIPT).expect("script.json");
    let home = FakeHome::new("gamelib-log-limiter-");
    let root = home.root().to_string_lossy().into_owned();
    let now = Arc::new(AtomicU64::new(BASE_MS));
    let logger = Logger::start(LogConfig {
        platform: Platform::current(),
        user_data: join(Platform::current(), &root, &["userData"]),
        log_dir: root.clone(),
        clock: Arc::new(ScriptClock(Arc::clone(&now))),
        tz: Arc::new(Utc),
    });
    for step in &script.steps {
        let ts = BASE_MS + step.t * 1000;
        now.store(ts, Ordering::SeqCst);
        if step.flush {
            assert!(logger.flush(Duration::from_secs(10)), "flush timed out");
            continue;
        }
        if let (Some(level), Some(prefix), Some(msg)) = (&step.level, &step.prefix, &step.msg) {
            let level = Level::from_str(level).expect("level");
            let prefix = Prefix::from_value(prefix).expect("prefix");
            logger.submit_line(ts, 0, level, prefix, msg);
        }
        // A tick step is the writer's own timer; a line step still needs the barrier.
        let what = if step.tick { "tick" } else { "barrier" };
        assert!(
            logger.tick_for_tests(Duration::from_secs(10)),
            "{what} timed out"
        );
    }
    assert!(
        logger.flush(Duration::from_secs(10)),
        "final flush timed out"
    );
    let got = fs::read_to_string(join(Platform::current(), &root, &["gamelib.log"]))
        .expect("gamelib.log");
    assert_eq!(got, EXPECTED);
}
