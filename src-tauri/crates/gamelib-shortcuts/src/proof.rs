//! Creation proofs (FND-02, D-22): before a Desktop item is cleared to make way for the link to the
//! Applications bundle, the crate proves GameLib wrote it. An item the proof cannot attribute to
//! GameLib is left where it is and reported (the 94-07 `addclear-*` deltas): the TypeScript removed
//! whatever stood there, a user's own file included.
//!
//! The proofs only read (`symlink_metadata`, `read_link`, bounded reads) and follow no link of the
//! item they judge.

use std::fs;
use std::io::Read;
use std::path::Path;

/// The line the macOS `run.sh` template carries.
const RUN_SH_MARKER: &str = "# autogenerated file - do not edit";
/// The scheme every GameLib launcher script opens.
const LAUNCH_SCHEME: &str = "gamelib://launch";
/// The line a GameLib `.desktop` file carries: `xdg-open` handing the launch URL to the protocol handler.
const DESKTOP_EXEC_PREFIX: &str = "Exec=xdg-open gamelib://launch?";
/// The group header every `.desktop` file GameLib writes opens with.
const DESKTOP_HEADER: &str = "[Desktop Entry]";
/// What a GameLib `.lnk` carries as its arguments, which a shell link stores as UTF-16LE.
const LNK_URL_PREFIX: &str = "gamelib://launch?appName=";
/// A generated script, plist, `.desktop` or `.lnk` is a few hundred bytes to a few KiB; anything past
/// this is not ours (and is never read past it).
const MAX_PROOF_BYTES: u64 = 64 * 1024;

/// True when `path` is a real directory (not a symlink to one).
fn is_real_dir(path: &Path) -> bool {
    fs::symlink_metadata(path).is_ok_and(|meta| meta.file_type().is_dir())
}

/// The bytes of `path` when it is a regular file (not a symlink) of a plausible size. Any failure to
/// look at it or read it is `None`: the caller refuses on unknown.
fn read_regular_bytes(path: &Path) -> Option<Vec<u8>> {
    let meta = fs::symlink_metadata(path).ok()?;
    if !meta.file_type().is_file() || meta.len() > MAX_PROOF_BYTES {
        return None;
    }
    let mut bytes = Vec::new();
    fs::File::open(path)
        .ok()?
        .take(MAX_PROOF_BYTES)
        .read_to_end(&mut bytes)
        .ok()?;
    Some(bytes)
}

/// The text of `path` when it is a regular file (not a symlink) of a plausible size and valid UTF-8.
fn read_regular_file(path: &Path) -> Option<String> {
    String::from_utf8(read_regular_bytes(path)?).ok()
}

/// True when the `Info.plist` text names `run.sh` as its `CFBundleExecutable`.
fn plist_executes_run_sh(plist: &str) -> bool {
    const KEY: &str = "<key>CFBundleExecutable</key>";
    let Some(at) = plist.find(KEY) else {
        return false;
    };
    plist[at + KEY.len()..]
        .trim_start()
        .starts_with("<string>run.sh</string>")
}

/// A macOS bundle GameLib wrote: a real directory whose `Contents/MacOS/run.sh` is a regular file
/// carrying GameLib's marker line and a `gamelib://launch` URL, and whose `Contents/Info.plist`
/// names `run.sh` as the executable. `Contents` and `Contents/MacOS` must be real directories, so a
/// bundle built from links into somewhere else never qualifies.
pub fn is_gamelib_bundle(path: &Path) -> bool {
    let contents = path.join("Contents");
    let macos = contents.join("MacOS");
    if !is_real_dir(path) || !is_real_dir(&contents) || !is_real_dir(&macos) {
        return false;
    }
    let Some(script) = read_regular_file(&macos.join("run.sh")) else {
        return false;
    };
    if !script.contains(RUN_SH_MARKER) || !script.contains(LAUNCH_SCHEME) {
        return false;
    }
    read_regular_file(&contents.join("Info.plist"))
        .is_some_and(|plist| plist_executes_run_sh(&plist))
}

/// A Desktop item GameLib created: a symlink whose target is exactly the Applications bundle path
/// (the target need not exist: a stale link from an earlier add still proves ours).
pub fn is_gamelib_desktop_link(link: &Path, bundle: &Path) -> bool {
    let is_link = fs::symlink_metadata(link).is_ok_and(|meta| meta.file_type().is_symlink());
    is_link && fs::read_link(link).is_ok_and(|target| target == bundle)
}

/// A Linux shortcut GameLib created: a regular file (never a symlink) that opens a `[Desktop Entry]` group
/// and holds an `Exec=xdg-open gamelib://launch?` line, as `desktop_entry` writes it. A file that cannot be
/// read, or is not UTF-8, is unknown and not ours.
pub fn is_gamelib_desktop_file(path: &Path) -> bool {
    read_regular_file(path).is_some_and(|text| {
        text.lines().any(|line| line == DESKTOP_HEADER)
            && text
                .lines()
                .any(|line| line.starts_with(DESKTOP_EXEC_PREFIX))
    })
}

/// A Windows shortcut GameLib created: a regular file (never a symlink) whose bytes contain the UTF-16LE
/// `gamelib://launch?appName=` its arguments carry. A file that cannot be read is unknown and not ours.
pub fn is_gamelib_lnk(path: &Path) -> bool {
    let needle: Vec<u8> = LNK_URL_PREFIX
        .encode_utf16()
        .flat_map(u16::to_le_bytes)
        .collect();
    read_regular_bytes(path).is_some_and(|bytes| {
        bytes
            .windows(needle.len())
            .any(|window| window == needle.as_slice())
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use gamelib_testutil::FakeHome;
    use std::path::PathBuf;

    const SCRIPT: &str =
        "#!/bin/bash\n    # autogenerated file - do not edit\n\n      \"/x\" --no-gui 'gamelib://launch?appName=a&runner=b'\n    ";
    const PLIST: &str =
        "<dict>\n\t\t<key>CFBundleExecutable</key>\n\t\t<string>run.sh</string>\n</dict>";

    fn bundle_with(home: &FakeHome, script: &str, plist: &str) -> PathBuf {
        let bundle = home.root().join("B.app");
        fs::create_dir_all(bundle.join("Contents").join("MacOS")).expect("dirs");
        fs::write(bundle.join("Contents").join("MacOS").join("run.sh"), script).expect("run.sh");
        fs::write(bundle.join("Contents").join("Info.plist"), plist).expect("plist");
        bundle
    }

    #[test]
    fn a_bundle_with_the_marker_the_scheme_and_the_plist_is_ours() {
        let home = FakeHome::new("gamelib-proof-");
        assert!(is_gamelib_bundle(&bundle_with(&home, SCRIPT, PLIST)));
    }

    #[test]
    fn a_bundle_missing_any_part_of_the_proof_is_not_ours() {
        let cases = [
            ("no marker", "#!/bin/bash\n'gamelib://launch?x'\n", PLIST),
            (
                "no scheme",
                "#!/bin/bash\n# autogenerated file - do not edit\n",
                PLIST,
            ),
            ("foreign script", "#!/bin/bash\necho foreign\n", PLIST),
            ("foreign plist", SCRIPT, "<plist/>\n"),
            (
                "another executable",
                SCRIPT,
                "<key>CFBundleExecutable</key><string>other</string>",
            ),
        ];
        for (what, script, plist) in cases {
            let home = FakeHome::new("gamelib-proof-");
            assert!(
                !is_gamelib_bundle(&bundle_with(&home, script, plist)),
                "{what}"
            );
        }
    }

    #[test]
    fn a_missing_path_a_file_and_an_oversized_script_are_not_bundles() {
        let home = FakeHome::new("gamelib-proof-");
        assert!(!is_gamelib_bundle(&home.root().join("absent.app")));
        let file = home.root().join("file.app");
        fs::write(&file, SCRIPT).expect("file");
        assert!(!is_gamelib_bundle(&file));
        let big = format!("{SCRIPT}{}", "x".repeat(MAX_PROOF_BYTES as usize));
        assert!(!is_gamelib_bundle(&bundle_with(&home, &big, PLIST)));
    }

    #[test]
    fn plist_executable_is_read_through_the_template_whitespace() {
        assert!(plist_executes_run_sh(PLIST));
        assert!(!plist_executes_run_sh("<string>run.sh</string>"));
        assert!(!plist_executes_run_sh(
            "<key>CFBundleExecutable</key>\n<string>run.shx</string>"
        ));
    }

    #[test]
    fn a_link_to_the_bundle_is_ours_and_a_link_elsewhere_is_not() {
        let home = FakeHome::new("gamelib-proof-");
        let bundle = home.root().join("Applications").join("G.app");
        let ours = home.root().join("ours");
        let theirs = home.root().join("theirs");
        let (made_ours, made_theirs) = (
            link(&bundle, &ours),
            link(&home.root().join("Elsewhere"), &theirs),
        );
        if !(made_ours && made_theirs) {
            return;
        }
        assert!(
            is_gamelib_desktop_link(&ours, &bundle),
            "dangling still ours"
        );
        assert!(!is_gamelib_desktop_link(&theirs, &bundle));
        assert!(!is_gamelib_desktop_link(
            &home.root().join("absent"),
            &bundle
        ));
    }

    #[test]
    fn a_regular_file_is_never_a_desktop_link() {
        let home = FakeHome::new("gamelib-proof-");
        let file = home.root().join("f");
        fs::write(&file, "x").expect("file");
        assert!(!is_gamelib_desktop_link(&file, &file));
    }

    #[test]
    fn a_bundle_whose_run_sh_is_a_link_is_not_ours() {
        let home = FakeHome::new("gamelib-proof-");
        let bundle = bundle_with(&home, SCRIPT, PLIST);
        let real = home.root().join("real.sh");
        fs::write(&real, SCRIPT).expect("script");
        let run_sh = bundle.join("Contents").join("MacOS").join("run.sh");
        fs::remove_file(&run_sh).expect("remove");
        if link(&real, &run_sh) {
            assert!(!is_gamelib_bundle(&bundle));
        }
    }

    const DESKTOP_FILE: &str = "[Desktop Entry]\nName=Plain Game\nExec=xdg-open gamelib://launch?appName=plainapp&runner=legendary\nTerminal=false\nType=Application\nCategories=Game;\n";

    fn utf16le(text: &str) -> Vec<u8> {
        text.encode_utf16().flat_map(u16::to_le_bytes).collect()
    }

    #[test]
    fn a_desktop_file_with_the_gamelib_exec_line_is_ours() {
        let home = FakeHome::new("gamelib-proof-");
        let file = home.root().join("G.desktop");
        fs::write(&file, DESKTOP_FILE).expect("file");
        assert!(is_gamelib_desktop_file(&file));
        // The Desktop copy and the menu copy differ only by an `Icon=` line.
        let with_icon = DESKTOP_FILE.replace("Categories", "Icon=/i/a.jpg\nCategories");
        fs::write(&file, with_icon).expect("file");
        assert!(is_gamelib_desktop_file(&file));
    }

    #[test]
    fn a_desktop_file_missing_any_part_of_the_proof_is_not_ours() {
        let cases = [
            (
                "foreign launcher",
                "[Desktop Entry]\nName=Foreign\nExec=/usr/bin/foreign\nType=Application\n",
            ),
            (
                "another opener",
                "[Desktop Entry]\nExec=xdg-open https://example.com\n",
            ),
            (
                "no header",
                "Exec=xdg-open gamelib://launch?appName=a&runner=b\n",
            ),
            (
                "the line is not at the start of a line",
                "[Desktop Entry]\n# Exec=xdg-open gamelib://launch?a\n Exec=xdg-open gamelib://launch?a\n",
            ),
            ("empty", ""),
        ];
        for (what, text) in cases {
            let home = FakeHome::new("gamelib-proof-");
            let file = home.root().join("G.desktop");
            fs::write(&file, text).expect("file");
            assert!(!is_gamelib_desktop_file(&file), "{what}");
        }
    }

    #[test]
    fn a_desktop_file_that_is_absent_unreadable_oversized_or_not_text_is_not_ours() {
        let home = FakeHome::new("gamelib-proof-");
        assert!(!is_gamelib_desktop_file(
            &home.root().join("absent.desktop")
        ));
        // A directory cannot be read as a file: unknown, so refused.
        let dir = home.root().join("dir.desktop");
        fs::create_dir_all(&dir).expect("dir");
        assert!(!is_gamelib_desktop_file(&dir));
        let big = home.root().join("big.desktop");
        fs::write(
            &big,
            format!("{DESKTOP_FILE}{}", "#".repeat(MAX_PROOF_BYTES as usize)),
        )
        .expect("big");
        assert!(!is_gamelib_desktop_file(&big));
        let binary = home.root().join("bin.desktop");
        let mut bytes = DESKTOP_FILE.as_bytes().to_vec();
        bytes.push(0xFF);
        fs::write(&binary, bytes).expect("binary");
        assert!(!is_gamelib_desktop_file(&binary));
    }

    #[test]
    fn a_desktop_file_that_is_a_link_is_never_ours_even_to_a_proven_file() {
        let home = FakeHome::new("gamelib-proof-");
        let real = home.root().join("real.desktop");
        fs::write(&real, DESKTOP_FILE).expect("real");
        let link_path = home.root().join("G.desktop");
        if link(&real, &link_path) {
            assert!(is_gamelib_desktop_file(&real));
            assert!(!is_gamelib_desktop_file(&link_path));
        }
    }

    #[test]
    fn a_lnk_holding_the_utf16le_launch_url_is_ours() {
        let home = FakeHome::new("gamelib-proof-");
        let file = home.root().join("G.lnk");
        let mut bytes = vec![0x4C, 0, 0, 0, 0x01, 0x14, 0x02, 0];
        bytes.extend(utf16le(
            "\"gamelib://launch?appName=plainapp&runner=legendary\"",
        ));
        fs::write(&file, bytes).expect("lnk");
        assert!(is_gamelib_lnk(&file));
    }

    #[test]
    fn a_lnk_without_the_utf16le_url_is_not_ours() {
        let cases: [(&str, Vec<u8>); 4] = [
            (
                "a foreign target",
                utf16le("C:\\Program Files\\Foreign\\foreign.exe"),
            ),
            (
                "the URL in a single-byte encoding",
                b"gamelib://launch?appName=a".to_vec(),
            ),
            ("another gamelib URL", utf16le("gamelib://other?appName=a")),
            ("empty", Vec::new()),
        ];
        for (what, bytes) in cases {
            let home = FakeHome::new("gamelib-proof-");
            let file = home.root().join("G.lnk");
            fs::write(&file, bytes).expect("lnk");
            assert!(!is_gamelib_lnk(&file), "{what}");
        }
    }

    #[test]
    fn a_lnk_that_is_absent_a_folder_oversized_or_a_link_is_not_ours() {
        let home = FakeHome::new("gamelib-proof-");
        assert!(!is_gamelib_lnk(&home.root().join("absent.lnk")));
        let dir = home.root().join("dir.lnk");
        fs::create_dir_all(&dir).expect("dir");
        assert!(!is_gamelib_lnk(&dir));
        let real = home.root().join("real.lnk");
        fs::write(&real, utf16le("gamelib://launch?appName=a")).expect("real");
        let mut big = utf16le("gamelib://launch?appName=a");
        big.resize(MAX_PROOF_BYTES as usize + 1, 0);
        let oversized = home.root().join("big.lnk");
        fs::write(&oversized, big).expect("big");
        assert!(!is_gamelib_lnk(&oversized));
        let link_path = home.root().join("G.lnk");
        if link(&real, &link_path) {
            assert!(is_gamelib_lnk(&real));
            assert!(!is_gamelib_lnk(&link_path));
        }
    }

    /// Makes a link; false when this host cannot (a skip locally, a panic on CI).
    fn link(target: &Path, link: &Path) -> bool {
        #[cfg(unix)]
        let made = std::os::unix::fs::symlink(target, link);
        #[cfg(windows)]
        let made = if target.is_dir() {
            std::os::windows::fs::symlink_dir(target, link)
        } else {
            std::os::windows::fs::symlink_file(target, link)
        };
        gamelib_testutil::require_link(made, "a proof symlink", std::env::var_os("CI").is_some())
    }
}
