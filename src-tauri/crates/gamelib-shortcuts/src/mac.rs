//! The macOS `.app` writer and the Desktop link. Ported from `generateMacOsApp` and
//! `linkDesktopToApplications` (`backend/shortcuts/shortcuts/shortcuts.ts`).
//!
//! One bundle is written, into `~/Applications`; the Desktop item is a plain symlink to it, so the
//! macOS Apps list shows the game once. The `Info.plist` and `run.sh` templates are the TypeScript's
//! own, whitespace and literal tabs included, and are pinned byte for byte by the `golden/text`
//! replay (D-14). `run.sh` double-quotes the executable path and single-quotes the percent-encoded
//! URL (T-34.5-C6-17), so `;`, `$()`, a backtick or a space in a name cannot run anything.
//!
//! One defect of that template is reproduced on purpose: `encodeURIComponent` leaves `'` alone, so
//! an app name holding an apostrophe closes the single quotes early and the launch breaks (not an
//! injection as measured; todo 2026-11-24-macos-shortcut-run-sh-breaks-on-single-quote-in-app-name).
//! The goldens pin those bytes, so the port keeps them until that todo is decided.

use std::fs;
use std::path::{Path, PathBuf};

use crate::ctx::{Platform, ShortcutPaths};
use crate::launch_url::launch_url;
use crate::paths::shortcut_files;
use crate::proof::{is_gamelib_bundle, is_gamelib_desktop_link};

/// The `Info.plist` up to and including the executable entry. The icon key pair, when there is one,
/// follows it; the rest of the plist is [`PLIST_TAIL`].
const PLIST_HEAD: &str = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\t<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n\t<plist version=\"1.0\">\n\t<dict>\n\t\t<key>CFBundleExecutable</key>\n\t\t<string>run.sh</string>";

/// The key pair present only when the icon was produced (D-04: the shortcut survives an
/// unobtainable icon, only this pair is conditional).
const PLIST_ICON_KEYS: &str = "\n\t<key>CFBundleIconFile</key>\n\t<string>shortcut.icns</string>";

const PLIST_TAIL: &str = "\n\t\t<key>CFBundleInfoDictionaryVersion</key>\n\t\t<string>1.0</string>\n\t\t<key>CFBundlePackageType</key>\n\t\t<string>APPL</string>\n\t\t<key>CFBundleSignature</key>\n\t\t<string>????</string>\n\t\t<key>CFBundleVersion</key>\n\t\t<string>1.0</string>\n\t</dict>\n\t</plist>\n  ";

/// `run.sh`'s mode (`chmodSync(..., '755')`): set outright, not subject to the umask.
#[cfg(unix)]
const RUN_SH_MODE: u32 = 0o755;

/// What [`write_mac_app`] wrote.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MacAppWritten {
    /// The `.app` directory under `~/Applications`.
    pub bundle: PathBuf,
    /// Whether `Contents/Resources/shortcut.icns` was produced and named in the `Info.plist`.
    pub icon: bool,
}

/// Why the Desktop item was not (re)linked.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DesktopRefused {
    /// Something is at the Desktop path that GameLib cannot prove it wrote (FND-02, D-22): left
    /// alone, nothing deleted.
    Unproven(PathBuf),
    /// The Desktop path or the bundle is not inside the profile the shell supplied.
    OutsideProfile(PathBuf),
    /// The link could not be made (or the Desktop folder, or the clear of a proven item).
    Io(String),
}

impl std::fmt::Display for DesktopRefused {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            DesktopRefused::Unproven(path) => write!(
                f,
                "not linked: {} is not a GameLib shortcut and was left in place",
                path.display()
            ),
            DesktopRefused::OutsideProfile(path) => {
                write!(f, "not linked: {} is outside the profile", path.display())
            }
            DesktopRefused::Io(error) => f.write_str(error),
        }
    }
}

impl std::error::Error for DesktopRefused {}

/// The `Info.plist` text, with the icon key pair when `with_icon`.
fn info_plist(with_icon: bool) -> String {
    let icon = if with_icon { PLIST_ICON_KEYS } else { "" };
    format!("{PLIST_HEAD}{icon}{PLIST_TAIL}")
}

/// The `run.sh` text for `shell_exe`, `app_name` and `runner`.
fn run_sh(shell_exe: &Path, app_name: &str, runner: &str) -> String {
    let url = launch_url(app_name, runner, true);
    let command = format!("\"{}\" --no-gui '{url}'", shell_exe.display());
    format!("#!/bin/bash\n    # autogenerated file - do not edit\n\n      {command}\n    ")
}

#[cfg(unix)]
fn make_executable(path: &Path) -> std::io::Result<()> {
    use std::os::unix::fs::PermissionsExt;
    fs::set_permissions(path, fs::Permissions::from_mode(RUN_SH_MODE))
}

#[cfg(not(unix))]
fn make_executable(_path: &Path) -> std::io::Result<()> {
    Ok(())
}

/// Writes the `.app` for `title` under `~/Applications`: `Contents/Info.plist`,
/// `Contents/MacOS/run.sh` (mode 755) and, when `icon_png` is given and converts, the
/// `Contents/Resources/shortcut.icns`. An icon that cannot be read or decoded gives the iconless
/// bundle, not an error (D-04, D-09 item 5). `icon_png` is whatever the icon lookup found (its
/// extension may say jpg: the decoder goes by content).
pub fn write_mac_app(
    paths: &ShortcutPaths,
    title: &str,
    app_name: &str,
    runner: &str,
    shell_exe: &Path,
    icon_png: Option<&Path>,
) -> Result<MacAppWritten, String> {
    let (_, menu) = shortcut_files(Platform::Mac, paths, title, None);
    let bundle = menu.ok_or_else(|| "no Applications path".to_string())?;
    let resources = bundle.join("Contents").join("Resources");
    let macos = bundle.join("Contents").join("MacOS");
    let io = |e: std::io::Error| e.to_string();

    fs::create_dir_all(&resources).map_err(io)?;
    let icon = write_icon(icon_png, &resources);

    fs::create_dir_all(&macos).map_err(io)?;
    fs::write(bundle.join("Contents").join("Info.plist"), info_plist(icon)).map_err(io)?;
    let script = macos.join("run.sh");
    fs::write(&script, run_sh(shell_exe, app_name, runner)).map_err(io)?;
    make_executable(&script).map_err(io)?;
    Ok(MacAppWritten { bundle, icon })
}

/// Converts `icon_png` into `resources/shortcut.icns`; false (iconless) when there is none or it
/// cannot be converted.
fn write_icon(icon_png: Option<&Path>, resources: &Path) -> bool {
    let _ = (icon_png, resources);
    false
}

/// Whether `path` is inside `root`, lexically (both come from the shell and the sanitized title).
fn inside(path: &Path, root: &Path) -> bool {
    path.starts_with(root)
}

#[cfg(unix)]
fn make_symlink(target: &Path, link: &Path) -> std::io::Result<()> {
    std::os::unix::fs::symlink(target, link)
}

#[cfg(windows)]
fn make_symlink(target: &Path, link: &Path) -> std::io::Result<()> {
    if target.is_dir() {
        std::os::windows::fs::symlink_dir(target, link)
    } else {
        std::os::windows::fs::symlink_file(target, link)
    }
}

#[cfg(not(any(unix, windows)))]
fn make_symlink(_target: &Path, _link: &Path) -> std::io::Result<()> {
    Err(std::io::Error::from(std::io::ErrorKind::Unsupported))
}

/// Removes a Desktop item already proven to be GameLib's: a symlink (unlinked, never followed) or a
/// real bundle directory (`remove_dir_all` does not follow links inside it).
fn clear_proven(item: &Path, is_link: bool) -> std::io::Result<()> {
    if !is_link {
        return fs::remove_dir_all(item);
    }
    // A directory symlink on Windows is removed with `remove_dir`, a file symlink with `remove_file`.
    fs::remove_file(item).or_else(|_| fs::remove_dir(item))
}

/// Points the Desktop item `desktop` at the Applications `bundle` with a plain symlink (no Finder
/// alias). What stands at `desktop` is cleared first only when GameLib wrote it (a legacy real
/// bundle that passes [`is_gamelib_bundle`], or a link to exactly `bundle`, dangling or not); any
/// other item is [`DesktopRefused::Unproven`] and nothing is deleted. Both paths must be inside
/// `paths.user_home`.
pub fn link_desktop(
    paths: &ShortcutPaths,
    desktop: &Path,
    bundle: &Path,
) -> Result<(), DesktopRefused> {
    for path in [desktop, bundle] {
        if !inside(path, &paths.user_home) {
            return Err(DesktopRefused::OutsideProfile(path.to_path_buf()));
        }
    }
    let io = |e: std::io::Error| DesktopRefused::Io(e.to_string());
    if let Some(parent) = desktop.parent() {
        fs::create_dir_all(parent).map_err(io)?;
    }
    match fs::symlink_metadata(desktop) {
        Ok(meta) => {
            let is_link = meta.file_type().is_symlink();
            let ours = if is_link {
                is_gamelib_desktop_link(desktop, bundle)
            } else {
                is_gamelib_bundle(desktop)
            };
            if !ours {
                return Err(DesktopRefused::Unproven(desktop.to_path_buf()));
            }
            clear_proven(desktop, is_link).map_err(io)?;
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
        Err(e) => return Err(io(e)),
    }
    make_symlink(bundle, desktop).map_err(io)
}
